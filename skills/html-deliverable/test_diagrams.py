class TheRestyling(unittest.TestCase):
    RAW = (
        '<?xml version="1.0"?>\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://x/svg11.dtd">\n'
        '<!-- Generated by something -->\n'
        '<svg width="400pt" height="300pt" viewBox="0 0 400 300">'
        "<style>@font-face { font-family: d2-font; src: url(data:font/woff;base64,AAAA); }\n"
        '.t { font-family: "d2-font"; }</style>'
        '<g class="node"><polygon fill="white" stroke="black"/><text>Box</text></g></svg>'
    )

    def setUp(self):
        self.out = build.restyle_svg(self.RAW, "graphviz", "u1")

    def test_the_standalone_wrapper_is_gone(self):
        self.assertNotIn("<?xml", self.out)
        self.assertNotIn("<!DOCTYPE", self.out)
        self.assertNotIn("Generated by", self.out)

    def test_the_embedded_font_and_its_rules_are_gone(self):
        self.assertNotIn("@font-face", self.out)
        self.assertNotIn("font-family", self.out)
        self.assertNotIn("base64", self.out)

    def test_the_fixed_pixel_size_is_dropped_but_the_viewbox_stays(self):
        self.assertNotIn('width="400pt"', self.out)
        self.assertNotIn('height="300pt"', self.out)
        self.assertIn('viewBox="0 0 400 300"', self.out)

    def test_the_wrapper_names_the_engine_and_the_block(self):
        self.assertIn('<div class="dgm-art" id="u1" data-engine="graphviz">', self.out)
        self.assertIn('class="dgm-svg"', self.out)

    def test_the_geometry_and_the_engine_classes_survive(self):
        """The recolor is CSS over presentation attributes, so the classes must still be there."""
        self.assertIn('class="node"', self.out)
        self.assertIn('fill="white"', self.out)


class TheHint(unittest.TestCase):
    def test_a_kind_with_no_caption(self):
        match = build.DIAGRAM_HINT_RE.search("<p>[diagram: tree]</p>\n<pre><code>A\n</code></pre>")
        self.assertEqual((match.group(1), match.group(2)), ("tree", None))

    def test_a_kind_with_a_caption(self):
        match = build.DIAGRAM_HINT_RE.search(
            "<p>[diagram: mindmap | What it holds]</p>\n<pre><code>A\n</code></pre>"
        )
        self.assertEqual((match.group(1), match.group(2)), ("mindmap", "What it holds"))

    def test_an_unknown_kind_names_the_kinds_that_exist(self):
        with self.assertRaises(SystemExit) as raised:
            build.diagram_blocks("<p>[diagram: gantt]</p>\n<pre><code>A\n</code></pre>")
        self.assertIn("flowchart", str(raised.exception))
        self.assertIn("mindmap", str(raised.exception))

    def test_a_fence_with_no_hint_is_left_as_a_code_block(self):
        source = "<pre><code>a -&gt; b\n</code></pre>"
        out, used = build.diagram_blocks(source)
        self.assertEqual((out, used), (source, False))



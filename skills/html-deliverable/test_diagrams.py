class TheLintGate(unittest.TestCase):
    """A diagram in a house deliverable is in the file, not on the network."""

    def failures(self, body: str) -> list[str]:
        return lint.check(page(body), money=False, allow_commands=True)[0]

    def test_an_image_of_a_diagram_fails(self):
        failures = self.failures('<section id="s1"><img src="https://example.com/chart.png"></section>')
        self.assertTrue(any("does not carry" in f for f in failures), failures)

    def test_a_relative_image_fails_too(self):
        failures = self.failures('<section id="s1"><img src="chart.png"></section>')
        self.assertTrue(any("does not carry" in f for f in failures), failures)

    def test_a_data_uri_image_is_fine(self):
        failures = self.failures('<section id="s1"><img src="data:image/png;base64,AAAA"></section>')
        self.assertEqual([f for f in failures if "does not carry" in f], [], failures)

    def test_a_cdn_diagram_script_fails(self):
        failures = self.failures(
            '<section id="s1"><script src="https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.min.js"></script></section>'
        )
        self.assertTrue(any("PRE-RENDERED" in f for f in failures), failures)

    def test_an_unrendered_diagram_element_fails(self):
        failures = self.failures('<section id="s1"><div class="mermaid">graph TD; A-->B;</div></section>')
        self.assertTrue(any("unrendered diagram element" in f for f in failures), failures)

    def test_a_runtime_initializer_fails(self):
        failures = self.failures('<section id="s1"><p>x</p></section><script>mermaid.initialize({});</script>')
        self.assertTrue(any("initializer" in f for f in failures), failures)

    def test_a_remote_frame_fails(self):
        failures = self.failures('<section id="s1"><iframe src="https://example.com/d"></iframe></section>')
        self.assertTrue(any("remote frame" in f for f in failures), failures)

    def test_prose_naming_an_engine_is_not_a_breach_of_the_rule(self):
        """The gallery and this skill's own pages talk about these engines by name."""
        failures = self.failures(
            '<section id="s1"><p>We compared Mermaid, Graphviz and Kroki before choosing.</p></section>'
        )
        self.assertEqual([f for f in failures if "PRE-RENDERED" in f], [], failures)


class TheRenderedDiagrams(unittest.TestCase):
    """The layer that actually shells out. Skipped, with the reason, when an engine is missing."""

    def render(self, kind: str, source: str, uid: str = "t1") -> str:
        reason = engine_ready(kind)
        if reason:
            self.skipTest(reason)
        return build.restyle_svg(build.run_engine(kind, source, uid), build.DIAGRAM_KINDS[kind]["engine"], uid)

    def test_every_kind_renders_to_inline_svg_that_fetches_nothing(self):
        for kind, source in (
            ("flowchart", FLOW),
            ("sequence", "A -> B: a question\nB -> A: the answer\n"),
            ("mindmap", OUTLINE),
            ("tree", OUTLINE),
        ):
            with self.subTest(kind=kind):
                art = self.render(kind, source)
                self.assertIn("<svg", art)
                self.assertIn(f'data-engine="{build.DIAGRAM_KINDS[kind]["engine"]}"', art)
                self.assertNotIn("<img", art)
                self.assertNotIn("<script", art)
                self.assertNotIn("http://", art.replace("http://www.w3.org", ""))
                self.assertNotIn("https://", art)

    def test_the_labels_the_author_wrote_are_in_the_picture(self):
        art = self.render("flowchart", FLOW)
        self.assertIn("A capture lands", art)
        self.assertIn("The classifier reads it", art)

    def test_two_diagrams_on_one_page_do_not_share_an_id(self):
        reason = engine_ready("flowchart")
        if reason:
            self.skipTest(reason)
        source = ("<p>[diagram: flowchart]</p>\n<pre><code>a -&gt; b\n</code></pre>\n"
                  "<p>[diagram: flowchart]</p>\n<pre><code>c -&gt; d\n</code></pre>")
        out, used = build.diagram_blocks(source, prefix="p-")
        self.assertTrue(used)
        ids = re.findall(r'class="dgm-art" id="([^"]+)"', out)
        self.assertEqual(ids, ["p-dgm1", "p-dgm2"])
        markers = set(re.findall(r'id="(mk-[^"]+)"', out))
        self.assertEqual(len(markers), len(set(markers)), "two svgs on one page reused an id")

    def test_a_built_page_ships_the_styles_carries_no_network_call_and_passes_the_lint(self):
        reason = engine_ready("flowchart")
        if reason:
            self.skipTest(reason)
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "d.md"
            source.write_text(
                "# A page with a picture\n\nThe lead paragraph.\n\n## The path\n\n"
                "[diagram: flowchart | How it moves]\n\n```\n" + FLOW + "```\n\n"
                "## After\n\nMore words, at https://example.com/one and https://example.com/two .\n",
                encoding="utf-8",
            )
            out = source.with_suffix(".html")
            self.assertEqual(build.main([str(source), str(out)]), 0)
            html = out.read_text(encoding="utf-8")
        self.assertIn(".dgm-art", html, "the diagram CSS did not ship with the page")
        self.assertIn('<figure class="dgm"', html)
        self.assertIn("<figcaption>How it moves</figcaption>", html)
        self.assertEqual(lint.check(html, money=False, allow_commands=True)[0], [])

    def test_the_caption_becomes_the_accessible_name(self):
        reason = engine_ready("tree")
        if reason:
            self.skipTest(reason)
        out, _ = build.diagram_blocks(
            "<p>[diagram: tree | The shape of it]</p>\n<pre><code>A\n  B\n</code></pre>"
        )
        self.assertIn('role="img"', out)
        self.assertIn('aria-label="The shape of it"', out)


class TheGalleryCarriesOneDemoPerKind(unittest.TestCase):
    def setUp(self):
        self.catalogue = {c.cid: c for c in build_gallery.COMPONENTS}
        self.gallery = (HERE / "components.html").read_text(encoding="utf-8")

    def test_one_component_per_kind(self):
        for kind in build.DIAGRAM_KINDS:
            with self.subTest(kind=kind):
                component = self.catalogue.get(f"diagram-{kind}")
                self.assertIsNotNone(component, f"the gallery has no demo for [diagram: {kind}]")
                self.assertEqual(component.diagram[0], kind)

    def test_the_built_gallery_carries_every_demo_and_its_markdown(self):
        for kind in build.DIAGRAM_KINDS:
            with self.subTest(kind=kind):
                self.assertIn(f'id="c-diagram-{kind}"', self.gallery, "rebuild the gallery")
                self.assertIn(f"[diagram: {kind} |", self.gallery, "the copy-paste markdown is missing")

    def test_the_gallery_ships_the_diagram_styles_once(self):
        self.assertIn(".dgm-art[data-engine=", self.gallery)
        self.assertEqual(self.gallery.count(".dgm-art{background:var(--panel-2)"), 1)

    def test_the_gallery_diagrams_are_real_inline_svg(self):
        self.assertGreaterEqual(self.gallery.count('class="dgm-art"'), len(build.DIAGRAM_KINDS))



#!/usr/bin/env python3
"""Tests for the `[diagram: <kind>]` blocks: the compile, the restyle, the gate, the gallery.

    python -m pytest skills/html-deliverable/test_diagrams.py

Two layers. The unit layer runs anywhere and needs no engine installed - it covers the outline
compiler, the sequence wrapper, the restyling pass and the lint gate. The render layer shells out
to d2 and graphviz and SKIPS with a named reason when they are not on this machine, because a
skill that refuses to run its own tests on a fresh checkout is a skill nobody keeps green.
"""

from __future__ import annotations

import re
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import build  # noqa: E402
import build_gallery  # noqa: E402
import lint  # noqa: E402

OUTLINE = """The system
  Capture
    Chat
  Route
    The board
"""
FLOW = "a: A capture lands\nb: The classifier reads it\na -> b: it is read\n"


def engine_ready(kind: str) -> str:
    """"" when the engine for `kind` is installed, otherwise the reason to skip."""
    spec = build.DIAGRAM_KINDS[kind]
    name = "d2" if spec["engine"] == "d2" else spec["layout"]
    try:
        build.diagram_binary(name, spec["engine"])
    except SystemExit as missing:
        return str(missing)
    return ""


def page(body: str) -> str:
    """A minimal page that satisfies every OTHER lint rule, so one check is under test."""
    return (
        '<!doctype html><html lang="en" data-theme="light" data-look="tint"><head><style>'
        ":root{--wrap-w:1080px}\n/* requestAnimationFrame */\n</style></head><body>"
        '<button class="grip l"></button><button class="grip r"></button>'
        '<nav id="sidenav"><button data-target="s1">A</button><button data-target="s2">B</button></nav>'
        f'<div class="wrap">{body}</div>'
        "<script>requestAnimationFrame(function(){});</script></body></html>"
    )


class TheOutlineCompiler(unittest.TestCase):
    def test_two_spaces_is_one_level(self):
        self.assertEqual(
            build.outline_rows("A\n  B\n    C\n  D\n"),
            [(0, "A"), (1, "B"), (2, "C"), (1, "D")],
        )

    def test_a_tab_bullets_blanks_and_comments_all_read(self):
        rows = build.outline_rows("A\n\t- B\n\n  # a note\n  * C\n")
        self.assertEqual(rows, [(0, "A"), (1, "B"), (1, "C")])

    def test_the_dot_carries_the_parent_edges_and_nothing_else(self):
        dot = build.outline_to_dot(OUTLINE, "twopi")
        self.assertIn("n0 -> n1;", dot)   # The system -> Capture
        self.assertIn("n1 -> n2;", dot)   # Capture -> Chat
        self.assertIn("n0 -> n3;", dot)   # The system -> Route  (not Chat -> Route)
        self.assertNotIn("n2 -> n3;", dot, "the outline popped back a level and the edge did not")

    def test_the_ground_polygon_is_never_painted(self):
        """Graphviz's white background renders as a white card behind a dark-theme diagram."""
        for layout in ("twopi", "dot"):
            self.assertIn("bgcolor=transparent;", build.outline_to_dot(OUTLINE, layout))

    def test_no_color_is_baked_into_the_dot(self):
        """A color in the DOT would beat the house token in one of the two themes."""
        dot = build.outline_to_dot(OUTLINE, "dot")
        self.assertNotIn("fillcolor", dot)
        self.assertNotIn("#", dot)

    def test_a_quote_in_a_label_cannot_break_out(self):
        dot = build.outline_to_dot('He said "go"\n  and went\n', "dot")
        self.assertIn(r'label="He said \"go\""', dot)

    def test_an_empty_outline_says_so(self):
        with self.assertRaises(SystemExit):
            build.outline_to_dot("\n\n", "dot")


